/*
 * compare to GForward() scores.
 */
static void
utest_fwdback(ESL_RANDOMNESS *r, ESL_ALPHABET *abc, P7_BG *bg, int M, int L, int N)
{
  char        *msg = "forward/backward unit test failed";
  P7_HMM      *hmm = NULL;
  P7_PROFILE  *gm  = NULL;
  P7_OPROFILE *om  = NULL;
  ESL_DSQ     *dsq = malloc(sizeof(ESL_DSQ) * (L+2));
  P7_OMX      *fwd = p7_omx_Create(M, 0, L);
  P7_OMX      *bck = p7_omx_Create(M, 0, L);
  P7_OMX      *oxf = p7_omx_Create(M, L, L);
  P7_OMX      *oxb = p7_omx_Create(M, L, L);
  P7_GMX      *gx  = p7_gmx_Create(M, L, L, p7G_NSCELLS);
  float tolerance;
  float fsc1, fsc2;
  float bsc1, bsc2;
  float generic_sc;

  p7_FLogsumInit();
  if (p7_FLogsumError(-0.4, -0.5) > 0.0001) tolerance = 1.0;  /* weaker test against GForward()   */
  else tolerance = 0.0001;   /* stronger test: FLogsum() is in slow exact mode. */

  p7_oprofile_Sample(r, abc, bg, M, L, &hmm, &gm, &om);
  while (N--)
    {
      esl_rsq_xfIID(r, bg->f, abc->K, L, dsq);

      p7_Forward       (dsq, L, om, oxf,      &fsc1);
      p7_Backward      (dsq, L, om, oxf, oxb, &bsc1);
      p7_ForwardParser (dsq, L, om, fwd,      &fsc2);
      p7_BackwardParser(dsq, L, om, fwd, bck, &bsc2);
      p7_GForward      (dsq, L, gm, gx,  &generic_sc);

      /* Forward and Backward scores should agree with high tolerance */
      if (fabs(fsc1-bsc1) > 0.0001)    esl_fatal(msg);
      if (fabs(fsc2-bsc2) > 0.0001)    esl_fatal(msg);
      if (fabs(fsc1-fsc2) > 0.0001)    esl_fatal(msg);

      /* GForward scores should approximate Forward scores,
       * with tolerance that depends on how logsum.c was compiled
       */
      if (fabs(fsc1-generic_sc) > tolerance) esl_fatal(msg);
    }

  free(dsq);
  p7_hmm_Destroy(hmm);
  p7_omx_Destroy(oxb);
  p7_omx_Destroy(oxf);
  p7_omx_Destroy(bck);
  p7_omx_Destroy(fwd);
  p7_gmx_Destroy(gx);
  p7_profile_Destroy(gm);
  p7_oprofile_Destroy(om);
}

/* utest_backward_decoding()
 * Compare p7_BackwardDecoding() with p7_Backward() followed by
 * p7_Decoding(). Both do the same products in the same order, so the
 * Backward scores must be equal and the posterior matrices identical.
 */
static void
utest_backward_decoding(ESL_RANDOMNESS *r, ESL_ALPHABET *abc, P7_BG *bg, int M, int L, int N)
{
  char        *msg  = "backward decoding unit test failed";
  P7_HMM      *hmm  = NULL;
  P7_PROFILE  *gm   = NULL;
  P7_OPROFILE *om   = NULL;
  ESL_DSQ     *dsq  = malloc(sizeof(ESL_DSQ) * (L+2));
  P7_OMX      *oxf  = p7_omx_Create(M, L, L);
  P7_OMX      *oxb  = p7_omx_Create(M, L, L);
  P7_OMX      *pp   = p7_omx_Create(M, L, L);
  P7_OMX      *fwd  = p7_omx_Create(M, L, L);
  P7_OMX      *bck  = p7_omx_Create(M, 0, L);
  P7_GMX      *gxp1 = p7_gmx_Create(M, L, L, p7G_NSCELLS);
  P7_GMX      *gxp2 = p7_gmx_Create(M, L, L, p7G_NSCELLS);
  float        bsc1, bsc2;
  int          i, x;

  p7_oprofile_Sample(r, abc, bg, M, L, &hmm, &gm, &om);
  while (N--)
    {
      esl_rsq_xfIID(r, bg->f, abc->K, L, dsq);

      if (p7_Forward         (dsq, L, om, oxf,      NULL)  != eslOK) esl_fatal(msg);
      if (p7_Backward        (dsq, L, om, oxf, oxb, &bsc1) != eslOK) esl_fatal(msg);
      if (p7_Decoding        (om, oxf, oxb, pp)            != eslOK) esl_fatal(msg);
      if (p7_Forward         (dsq, L, om, fwd,      NULL)  != eslOK) esl_fatal(msg);
      if (p7_BackwardDecoding(dsq, L, om, fwd, bck, &bsc2) != eslOK) esl_fatal(msg);
      if (p7_omx_FDeconvert(pp,  gxp1)                     != eslOK) esl_fatal(msg);
      if (p7_omx_FDeconvert(fwd, gxp2)                     != eslOK) esl_fatal(msg);

      if (bsc1 != bsc2)                                              esl_fatal("%s: Backward scores differ (%f %f)", msg, bsc1, bsc2);
      if (p7_gmx_Compare(gxp2, gxp1, 0.0)                  != eslOK) esl_fatal("%s: posterior matrices differ", msg);
      for (i = 0; i <= L; i++)
        for (x = 0; x < p7X_NXCELLS; x++)
          if (bck->xmx[i*p7X_NXCELLS+x] != oxb->xmx[i*p7X_NXCELLS+x]) esl_fatal("%s: Backward special states differ", msg);
    }

  free(dsq);
  p7_hmm_Destroy(hmm);
  p7_omx_Destroy(oxf);
  p7_omx_Destroy(oxb);
  p7_omx_Destroy(pp);
  p7_omx_Destroy(fwd);
  p7_omx_Destroy(bck);
  p7_gmx_Destroy(gxp1);
  p7_gmx_Destroy(gxp2);
  p7_profile_Destroy(gm);
  p7_oprofile_Destroy(om);
}

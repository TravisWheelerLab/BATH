/* Function:  p7_BackwardDecoding()
 * Synopsis:  The Backward parser with posterior decoding.
 *
 * Purpose:   Same as <p7_BackwardParser()>, and in addition writes the
 *            posterior decoding over the Forward matrix <fwd>, as the
 *            Backward rows are finished from <L> down. On return <fwd>
 *            holds the posterior decoding matrix <p7_Decoding()> would
 *            produce, and <bck> holds the Backward special states for
 *            all rows.
 *
 *            <fwd> must be a full Forward matrix filled by
 *            <p7_Forward()>. The caller provides a "parsing" <bck>, as
 *            for <p7_BackwardParser()>, by calling
 *            <bck = p7_omx_Create(M, 0, L)> or
 *            <p7_omx_GrowTo(bck, M, 0, L)>.
 *
 * Args:      dsq     - digital target sequence, 1..L
 *            L       - length of dsq in residues
 *            om      - optimized profile
 *            fwd     - filled Forward DP matrix; RESULT: posterior decoding matrix
 *            bck     - RETURN: Backward special states
 *            opt_sc  - optRETURN: Backward score (in nats)
 *
 * Returns:   <eslOK> on success.
 *            <eslERANGE> if the posterior scaling overflows, as for
 *            <p7_Decoding()>.
 *
 * Throws:    <eslEINVAL> if <bck> or <fwd> allocation is too small, or if
 *            the profile isn't in local alignment mode.
 *            <eslERANGE> if the score exceeds the limited range of
 *            a probability-space odds ratio.
 *            In either case, <*opt_sc> is undefined.
 */
int
p7_BackwardDecoding(const ESL_DSQ *dsq, int L, const P7_OPROFILE *om, P7_OMX *fwd, P7_OMX *bck, float *opt_sc)
{
#if eslDEBUGLEVEL > 0
  if (om->M >  bck->allocQ4*4)    ESL_EXCEPTION(eslEINVAL, "DP matrix allocated too small (too few columns)");
  if (bck->validR < 1)            ESL_EXCEPTION(eslEINVAL, "DP matrix allocated too small (too few MDI rows)");
  if (L     >= bck->allocXR)      ESL_EXCEPTION(eslEINVAL, "DP matrix allocated too small (too few X rows)");
  if (L     != fwd->L)            ESL_EXCEPTION(eslEINVAL, "fwd matrix size doesn't agree with length L");
  if (L     >= fwd->validR)       ESL_EXCEPTION(eslEINVAL, "fwd matrix isn't a full matrix (too few MDI rows)");
  if (! p7_oprofile_IsLocal(om))  ESL_EXCEPTION(eslEINVAL, "Forward implementation makes assumptions that only work for local alignment");
#endif

  return backward_engine(FALSE, dsq, L, om, fwd, bck, fwd, opt_sc);
}



/*****************************************************************
 * 2. Forward/Backward engine implementations (called thru API)
 *****************************************************************/

static int
forward_engine(int do_full, const ESL_DSQ *dsq, int L, const P7_OPROFILE *om, P7_OMX *ox, float *opt_sc)
{
  register float32x4_t mpv, dpv, ipv;  /* previous row values                                       */
  register float32x4_t sv;		         /* temp storage of 1 curr row value in progress              */
  register float32x4_t dcv;		         /* delayed storage of D(i,q+1)                               */
  register float32x4_t xEv;		         /* E state: keeps max for Mk->E as we go                     */
  register float32x4_t xBv;		         /* B state: splatted vector of B[i-1] for B->Mk calculations */
  register float32x4_t zerov;          /* zero vector: used for emulating logical shifts with VEXT  */
  float    xN, xE, xB, xC, xJ;	       /* special states' scores                                    */
  int i;			                         /* counter over sequence positions 1..L                      */
  int q;			                         /* counter over quads 0..nq-1                                */
  int j;			                         /* counter over DD iterations (4 is full serialization)      */
  int Q       = p7O_NQF(om->M);	       /* segment length: # of vectors                              */
  float32x4_t *dpc = ox->dpf[0];       /* current row, for use in {MDI}MO(dpp,q) access macro       */
  float32x4_t *dpp;                    /* previous row, for use in {MDI}MO(dpp,q) access macro      */
  float32x4_t *rp;			               /* will point at om->rfv[x] for residue x[i]                 */
  float32x4_t *tp;			               /* will point into (and step thru) om->tfv                   */

  /* Initialization. */
  zerov = vmovq_n_f32(0.0);
  ox->M  = om->M;
  ox->L  = L;
  ox->has_own_scales = TRUE; 	/* all forward matrices control their own scalefactors */
  for (q = 0; q < Q; q++)
    MMO(dpc,q) = IMO(dpc,q) = DMO(dpc,q) = zerov;
  xE    = ox->xmx[p7X_E] = 0.;
  xN    = ox->xmx[p7X_N] = 1.;
  xJ    = ox->xmx[p7X_J] = 0.;
  xB    = ox->xmx[p7X_B] = om->xf[p7O_N][p7O_MOVE];
  xC    = ox->xmx[p7X_C] = 0.;

  ox->xmx[p7X_SCALE] = 1.0;
  ox->totscale       = 0.0;

#if eslDEBUGLEVEL > 0
  if (ox->debugging) p7_omx_DumpFBRow(ox, TRUE, 0, 9, 5, xE, xN, xJ, xB, xC);	/* logify=TRUE, <rowi>=0, width=8, precision=5*/
#endif

  for (i = 1; i <= L; i++)
    {
      dpp = dpc;
      dpc = ox->dpf[do_full * i];     /* avoid conditional, use do_full as kronecker delta */
      rp  = om->rfv[dsq[i]];
      tp  = om->tfv;
      dcv = vmovq_n_f32(0.0f);
      xEv = vmovq_n_f32(0.0f);
      xBv = vmovq_n_f32(xB);

      /* Right shifts by 4 bytes. 4,8,12,x becomes x,4,8,12.  Shift zeros on. */
      mpv = vextq_f32(zerov, MMO(dpp,Q-1), 3);
      dpv = vextq_f32(zerov, DMO(dpp,Q-1), 3);
      ipv = vextq_f32(zerov, IMO(dpp,Q-1), 3);

      for (q = 0; q < Q; q++) {
	      /* Calculate new MMO(i,q); don't store it yet, hold it in sv. */
	      sv  =               vmulq_f32(xBv, *tp);  tp++;
#ifdef ARMDEBUG
        printf("i= %d, q=%d, step=1 ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)sv);
        printf("\n");
#endif
        sv  = vaddq_f32(sv, vmulq_f32(mpv, *tp)); tp++;
#ifdef ARMDEBUG
        printf("i= %d, q=%d, step=2 ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)sv);
        printf("\n");
#endif
        sv  = vaddq_f32(sv, vmulq_f32(ipv, *tp)); tp++;
#ifdef ARMDEBUG
        printf("i= %d, q=%d, step=3 ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)sv);
        printf("\n");
#endif
        sv  = vaddq_f32(sv, vmulq_f32(dpv, *tp)); tp++;
#ifdef ARMDEBUG
        printf("i= %d, q=%d, step=4 ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)sv);
        printf("\n");
#endif
#ifdef ARMDEBUG
        printf("i= %d, q=%d, rp=", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)*rp);
        printf("\n");
#endif
        sv  = vmulq_f32(sv, *rp);                 rp++;
#ifdef ARMDEBUG
        printf("i= %d, q=%d, step=5 ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)sv);
        printf("\n");
#endif
        xEv = vaddq_f32(xEv, sv);
#ifdef ARMDEBUG
        printf("i= %d, q=%d, ", i, q);
        esl_neon_dump_float(stdout, (esl_neon_128f_t)xEv);
        printf("\n");
#endif
        /* Load {MDI}(i-1,q) into mpv, dpv, ipv;
	      * {MDI}MX(q) is then the current, not the prev row
	      */
	      mpv = MMO(dpp,q);
	      dpv = DMO(dpp,q);
	      ipv = IMO(dpp,q);

	      /* Do the delayed stores of {MD}(i,q) now that memory is usable */
	      MMO(dpc,q) = sv;
	      DMO(dpc,q) = dcv;

	      /* Calculate the next D(i,q+1) partially: M->D only;
           * delay storage, holding it in dcv
	      */
	      dcv = vmulq_f32(sv, *tp); tp++;

	      /* Calculate and store I(i,q); assumes odds ratio for emission is 1.0 */
	      sv         =               vmulq_f32(mpv, *tp);  tp++;
	      IMO(dpc,q) = vaddq_f32(sv, vmulq_f32(ipv, *tp)); tp++;
	    }
#ifdef ARMDEBUG
      printf("i= %d, step = 1, ", i);
      esl_neon_dump_float(stdout, (esl_neon_128f_t) xEv);
      printf("\n");
#endif
      /* Now the DD paths. We would rather not serialize them but
       * in an accurate Forward calculation, we have few options.
       */
      /* dcv has carried through from end of q loop above; store it
       * in first pass, we add M->D and D->D path into DMX
       */
      /* We're almost certainly obligated to do at least one complete
       * DD path to be sure:
       */
      dcv        = vextq_f32(zerov, dcv, 3);
      DMO(dpc,0) = vmovq_n_f32(0.0);
      tp         = om->tfv + 7*Q;	/* set tp to start of the DD's */
      for (q = 0; q < Q; q++) {
    	  DMO(dpc,q) = vaddq_f32(dcv, DMO(dpc,q));
	      dcv        = vmulq_f32(DMO(dpc,q), *tp); tp++; /* extend DMO(q), so we include M->D and D->D paths */
	    }

      /* now. on small models, it seems best (empirically) to just go
       * ahead and serialize. on large models, we can do a bit better,
       * by testing for when dcv (DD path) accrued to DMO(q) is below
       * machine epsilon for all q, in which case we know DMO(q) are all
       * at their final values. The tradeoff point is (empirically) somewhere around M=100,
       * at least on my desktop. We don't worry about the conditional here;
       * it's outside any inner loops.
       */
      if (om->M < 100){			/* Fully serialized version */
	      for (j = 1; j < 4; j++){
          dcv = vextq_f32(zerov, dcv, 3);
	        tp        = om->tfv + 7*Q;	/* set tp to start of the DD's */
	        for (q = 0; q < Q; q++){ /* note, extend dcv, not DMO(q); only adding DD paths now */
		        DMO(dpc,q) = vaddq_f32(dcv, DMO(dpc,q));
		        dcv        = vmulq_f32(dcv, *tp);   tp++;
		      }
	      }
	    }
      else {			/* Slightly parallelized version, but which incurs some overhead */
	      for (j = 1; j < 4; j++) {
	        register uint32x4_t cv;	/* keeps track of whether any DD's change DMO(q) */

          dcv = vextq_f32(zerov, dcv, 3);
	        tp  = om->tfv + 7*Q;	/* set tp to start of the DD's */
	        cv  = vmovq_n_u32(0);
	        for (q = 0; q < Q; q++){ /* using cmpgt below tests if DD changed any DMO(q) *without* conditional branch */
		        sv         = vaddq_f32(dcv, DMO(dpc,q));
		        cv         = vorrq_u32(cv, vcgtq_f32(sv, DMO(dpc,q)));
		        DMO(dpc,q) = sv;	                              /* store new DMO(q) */
		        dcv        = vmulq_f32(dcv, *tp);   tp++;       /* note, extend dcv, not DMO(q) */
		      }
	        if (esl_neon_hmax_u8((esl_neon_128i_t) cv) == 0) break; /* DD's didn't change any DMO(q)? Then done, break out. */
	      }
	    }
#ifdef ARMDEBUG
      printf("i= %d, step = 2, ", i);
      esl_neon_dump_float(stdout, (esl_neon_128f_t) xEv);
      printf("\n");
#endif
      /* Add D's to xEv */
      for (q = 0; q < Q; q++) xEv = vaddq_f32(DMO(dpc,q), xEv);

      /* Finally the "special" states, which start from Mk->E (->C, ->J->B) */
      /* The following incantation is a horizontal sum of xEv's elements  */
      /* These must follow DD calculations, because D's contribute to E in Forward
       * (as opposed to Viterbi)
       */
      esl_neon_hsum_float((esl_neon_128f_t) xEv, &xE);
      xN =  xN * om->xf[p7O_N][p7O_LOOP];
      xC = (xC * om->xf[p7O_C][p7O_LOOP]) +  (xE * om->xf[p7O_E][p7O_MOVE]);
      xJ = (xJ * om->xf[p7O_J][p7O_LOOP]) +  (xE * om->xf[p7O_E][p7O_LOOP]);
      xB = (xJ * om->xf[p7O_J][p7O_MOVE]) +  (xN * om->xf[p7O_N][p7O_MOVE]);
      /* and now xB will carry over into next i, and xC carries over after i=L */

      /* Sparse rescaling. xE above threshold? trigger a rescaling event.            */
      if (xE > 1.0e4)	/* that's a little less than e^10, ~10% of our dynamic range */{
	    xN  = xN / xE;
	    xC  = xC / xE;
	    xJ  = xJ / xE;
	    xB  = xB / xE;

      xEv = vmovq_n_f32(1.0 / xE);
      for (q = 0; q < Q; q++){
	      MMO(dpc,q) = vmulq_f32(MMO(dpc,q), xEv);
	      DMO(dpc,q) = vmulq_f32(DMO(dpc,q), xEv);
	      IMO(dpc,q) = vmulq_f32(IMO(dpc,q), xEv);
	    }
  	  ox->xmx[i*p7X_NXCELLS+p7X_SCALE] = xE;
	    ox->totscale += log(xE);
	    xE = 1.0;
	    }
      else ox->xmx[i*p7X_NXCELLS+p7X_SCALE] = 1.0;

      /* Storage of the specials.  We could've stored these already
       * but using xE, etc. variables makes it easy to convert this
       * code to O(M) memory versions just by deleting storage steps.
       */
      ox->xmx[i*p7X_NXCELLS+p7X_E] = xE;
      ox->xmx[i*p7X_NXCELLS+p7X_N] = xN;
      ox->xmx[i*p7X_NXCELLS+p7X_J] = xJ;
      ox->xmx[i*p7X_NXCELLS+p7X_B] = xB;
      ox->xmx[i*p7X_NXCELLS+p7X_C] = xC;

#if eslDEBUGLEVEL > 0
      if (ox->debugging) p7_omx_DumpFBRow(ox, TRUE, i, 9, 5, xE, xN, xJ, xB, xC);	/* logify=TRUE, <rowi>=i, width=8, precision=5*/
#endif
#ifdef ARMDEBUG
      printf("i= %d, xE = %f\n", i, xE);
#endif
    } /* end loop over sequence residues 1..L */

  /* finally C->T, and flip total score back to log space (nats) */
  /* On overflow, xC is inf or nan (nan arises because inf*0 = nan). */
  /* On an underflow (which shouldn't happen), we counterintuitively return infinity:
   * the effect of this is to force the caller to rescore us with full range.
   */
  if       (isnan(xC))        ESL_EXCEPTION(eslERANGE, "forward score is NaN");
  else if  (L>0 && xC == 0.0) ESL_EXCEPTION(eslERANGE, "forward score underflow (is 0.0)");     /* if L==0, xC *should* be 0.0; J5/118 */
  else if  (isinf(xC) == 1)   ESL_EXCEPTION(eslERANGE, "forward score overflow (is infinity)");

  if (opt_sc != NULL) *opt_sc = ox->totscale + log(xC * om->xf[p7O_C][p7O_MOVE]);
  return eslOK;
}



/* backward_decode_row()
 * For backward_engine() with a posterior matrix <pp>, which is the
 * Forward matrix <fwd>: as soon as Backward row <i> (<dpc>, and the
 * special states in <bck>) is final, write F*B for M and I over row <i>
 * of <pp>, 0 for D, and F(i-1)*B(i)*t_loop for N, J and C. The engine
 * multiplies each row by its scale product after the sweep, completing
 * the same products, in the same order, as p7_Decoding(). Posterior
 * row <i> reads Forward row <i> and the Forward special states of row
 * <i-1>, which are not overwritten yet when the rows are done from L
 * down.
 */
static inline void
backward_decode_row(const P7_OPROFILE *om, const P7_OMX *fwd, const P7_OMX *bck, float32x4_t *dpc, P7_OMX *pp, int i, int Q)
{
  float32x4_t *ppv = pp->dpf[i];
  float32x4_t *fv  = fwd->dpf[i];
  int q;

  for (q = 0; q < Q; q++)
    {
      MMO(ppv,q) = vmulq_f32(MMO(fv,q), MMO(dpc,q));
      DMO(ppv,q) = vmovq_n_f32(0.0);
      IMO(ppv,q) = vmulq_f32(IMO(fv,q), IMO(dpc,q));
    }
  pp->xmx[i*p7X_NXCELLS+p7X_E] = 0.0;
  pp->xmx[i*p7X_NXCELLS+p7X_N] = fwd->xmx[(i-1)*p7X_NXCELLS+p7X_N] * bck->xmx[i*p7X_NXCELLS+p7X_N] * om->xf[p7O_N][p7O_LOOP];
  pp->xmx[i*p7X_NXCELLS+p7X_J] = fwd->xmx[(i-1)*p7X_NXCELLS+p7X_J] * bck->xmx[i*p7X_NXCELLS+p7X_J] * om->xf[p7O_J][p7O_LOOP];
  pp->xmx[i*p7X_NXCELLS+p7X_C] = fwd->xmx[(i-1)*p7X_NXCELLS+p7X_C] * bck->xmx[i*p7X_NXCELLS+p7X_C] * om->xf[p7O_C][p7O_LOOP];
  pp->xmx[i*p7X_NXCELLS+p7X_B] = 0.0;
}

/* Scale factor a Backward row takes, for backward_row_L() and
 * backward_row():
 *   BWD_SCALE_FORWARD: the Forward matrix's factor for the row, or the
 *     row's own factor once its xB has exceeded 1e16 (p7_Backward());
 *   BWD_SCALE_OWN:     the row's own factor, xB when xB > 1e4, else 1;
 *   BWD_SCALE_STORED:  the factor already stored for the row, when a
 *     row is computed again.
 */
enum bwd_scale_e { BWD_SCALE_FORWARD = 0, BWD_SCALE_OWN = 1, BWD_SCALE_STORED = 2 };


/* backward_row_L()
 * Backward row <L> into <dpc>, special states and scale factor into
 * row <L> of <xmx>. <fwd_xmx> holds the Forward special states and
 * scale factors (needed only for BWD_SCALE_FORWARD). If <totscale> is
 * non-NULL it is set to the log of the row's scale factor.
 */
static void
backward_row_L(const P7_OPROFILE *om, const float *fwd_xmx, float *xmx, float *totscale, float32x4_t *dpc, int L, int scale_mode)
{
  register float32x4_t dpv;
  register float32x4_t dcv;
  register float32x4_t xEv;
  register float32x4_t zerov;
  float xN, xE, xB, xC, xJ;
  int q;
  int Q       = p7O_NQF(om->M);
  int j;
  float32x4_t *tp;
  float    sc;

  zerov = vmovq_n_f32(0.0);
  xJ  = 0.0;
  xB  = 0.0;
  xN  = 0.0;
  xC  = om->xf[p7O_C][p7O_MOVE];      /* C<-T */
  xE  = xC * om->xf[p7O_E][p7O_MOVE]; /* E<-C, no tail */
  xEv = vmovq_n_f32(xE);
  dcv = vmovq_n_f32(0.0);		/* solely to silence a compiler warning */
  for (q = 0; q < Q; q++) MMO(dpc,q) = DMO(dpc,q) = xEv;
  for (q = 0; q < Q; q++) IMO(dpc,q) = zerov;

  /* init row L's DD paths, 1) first segment includes xE, from DMO(q) */
  tp  = om->tfv + 8*Q - 1;	                        /* <*tp> now the [4 8 12 x] TDD quad         */
  dpv = vextq_f32(DMO(dpc,Q-1), zerov, 1);          /* leftshift:[x 5 9 13] -> [5 9 13 x] */
  for (q = Q-1; q >= 0; q--)
    {
      dcv        = vmulq_f32(dpv, *tp); tp--;
      DMO(dpc,q) = vaddq_f32(DMO(dpc,q), dcv);
      dpv        = DMO(dpc,q);
    }
  /* 2) three more passes, only extending DD component (dcv only; no xE contrib from DMO(q)) */
  for (j = 1; j < 4; j++)
    {
      tp  = om->tfv + 8*Q - 1;	          /* <*tp> now the [4 8 12 x] TDD quad         */
      dcv = vextq_f32(dcv, zerov, 1);     /* leftshift:[x 5 9 13] -> [5 9 13 x] */
      for (q = Q-1; q >= 0; q--)
	{
	  dcv        = vmulq_f32(dcv, *tp); tp--;
	  DMO(dpc,q) = vaddq_f32(DMO(dpc,q), dcv);
	}
    }
  /* now MD init */
  tp  = om->tfv + 7*Q - 3;	                  /* <*tp> now the [4 8 12 x] Mk->Dk+1 quad    */
  dcv = vextq_f32(DMO(dpc, 0), zerov, 1);     /* leftshift:[x 5 9 13] -> [5 9 13 x] */
  for (q = Q-1; q >= 0; q--)
    {
      MMO(dpc,q) = vaddq_f32(MMO(dpc,q), vmulq_f32(dcv, *tp)); tp -= 7;
      dcv        = DMO(dpc,q);
    }

  /* Sparse rescaling: same scale factors as fwd matrix */
  if      (scale_mode == BWD_SCALE_FORWARD) sc = fwd_xmx[L*p7X_NXCELLS+p7X_SCALE];
  else if (scale_mode == BWD_SCALE_OWN)     sc = (xB > 1.0e4) ? xB : 1.0;
  else                                      sc = xmx[L*p7X_NXCELLS+p7X_SCALE];
  if (sc > 1.0)
    {
      xE  = xE / sc;
      xN  = xN / sc;
      xC  = xC / sc;
      xJ  = xJ / sc;
      xB  = xB / sc;
      xEv = vmovq_n_f32(1.0 / sc);
      for (q = 0; q < Q; q++) {
	MMO(dpc,q) = vmulq_f32(MMO(dpc,q), xEv);
	DMO(dpc,q) = vmulq_f32(DMO(dpc,q), xEv);
	IMO(dpc,q) = vmulq_f32(IMO(dpc,q), xEv);
      }
    }
  xmx[L*p7X_NXCELLS+p7X_SCALE] = sc;
  if (totscale != NULL) *totscale = log(xmx[L*p7X_NXCELLS+p7X_SCALE]);

  /* Stores */
  xmx[L*p7X_NXCELLS+p7X_E] = xE;
  xmx[L*p7X_NXCELLS+p7X_N] = xN;
  xmx[L*p7X_NXCELLS+p7X_J] = xJ;
  xmx[L*p7X_NXCELLS+p7X_B] = xB;
  xmx[L*p7X_NXCELLS+p7X_C] = xC;
}


/* backward_row()
 * Backward row <i> (1 <= i < L) into <dpc> from row <i>+1 in <dpp>,
 * reading the special states of row <i>+1 from <xmx> and writing row
 * <i>'s special states and scale factor into it. <fwd_xmx> holds the
 * Forward special states and scale factors (needed only for
 * BWD_SCALE_FORWARD). If <totscale> is non-NULL the log of a scale
 * factor > 1 is added to it. <has_own_scales> is the flag that
 * BWD_SCALE_FORWARD turns on once xB exceeds 1e16.
 */
static void
backward_row(const ESL_DSQ *dsq, const P7_OPROFILE *om, const float *fwd_xmx, float *xmx, float *totscale, int *has_own_scales,
             float32x4_t *dpc, const float32x4_t *dpp, int i, int scale_mode)
{
  register float32x4_t mpv, ipv, dpv;
  register float32x4_t mcv, dcv;
  register float32x4_t tmmv, timv, tdmv;
  register float32x4_t xBv;
  register float32x4_t xEv;
  register float32x4_t zerov;
  float xN, xE, xB, xC, xJ;
  int q;
  int Q       = p7O_NQF(om->M);
  int j;
  float32x4_t *rp;
  float32x4_t *tp;

  zerov = vmovq_n_f32(0.0);
  xN = xmx[(i+1)*p7X_NXCELLS+p7X_N];
  xJ = xmx[(i+1)*p7X_NXCELLS+p7X_J];
  xC = xmx[(i+1)*p7X_NXCELLS+p7X_C];

  rp  = om->rfv[dsq[i+1]] + Q-1; /* <*rp> is now the [4 8 12 x] match emission quad */
  tp  = om->tfv + 7*Q - 1;	     /* <*tp> is now the [4 8 12 x] TII transition quad  */

  /* leftshift the first transition quads */
  tmmv = vextq_f32(om->tfv[1], zerov, 1);
  timv = vextq_f32(om->tfv[2], zerov, 1);
  tdmv = vextq_f32(om->tfv[3], zerov, 1);

  mpv = vmulq_f32(MMO(dpp,0), om->rfv[dsq[i+1]][0]); /* precalc M(i+1,k+1) * e(M_k+1, x_{i+1}) */
  mpv = vextq_f32(mpv, zerov, 1);

  xBv = vmovq_n_f32(0.0);
  for (q = Q-1; q >= 0; q--)     /* backwards stride */
	{
	  ipv        = IMO(dpp,q); /* assumes emission odds ratio of 1.0; i+1's IMO(q) now free */
	  IMO(dpc,q) = vaddq_f32(vmulq_f32(ipv, *tp), vmulq_f32(mpv, timv)); tp--;
	  DMO(dpc,q) =                                vmulq_f32(mpv, tdmv);
	  mcv        = vaddq_f32(vmulq_f32(ipv, *tp), vmulq_f32(mpv, tmmv)); tp-= 2;

	  mpv        = vmulq_f32(MMO(dpp,q), *rp);  rp--;  /* obtain mpv for next q. i+1's MMO(q) is freed  */
	  MMO(dpc,q) = mcv;

	  tdmv = *tp;   tp--;
	  timv = *tp;   tp--;
	  tmmv = *tp;   tp--;

	  xBv = vaddq_f32(xBv, vmulq_f32(mpv, *tp)); tp--;
	}

  /* phase 2: now that we have accumulated the B->Mk transitions in xBv, we can do the specials */
  esl_neon_hsum_float((esl_neon_128f_t) xBv, &xB);
  xBv = vmovq_n_f32(xB);

  xC  =  xC * om->xf[p7O_C][p7O_LOOP];
  xJ  = (xB * om->xf[p7O_J][p7O_MOVE]) + (xJ * om->xf[p7O_J][p7O_LOOP]); /* must come after xB */
  xN  = (xB * om->xf[p7O_N][p7O_MOVE]) + (xN * om->xf[p7O_N][p7O_LOOP]); /* must come after xB */
  xE  = (xC * om->xf[p7O_E][p7O_MOVE]) + (xJ * om->xf[p7O_E][p7O_LOOP]); /* must come after xJ, xC */
  xEv = vmovq_n_f32(xE);	/* splat */


  /* phase 3: {MD}->E paths and one step of the D->D paths */
  tp  = om->tfv + 8*Q - 1;	/* <*tp> now the [4 8 12 x] TDD quad */
  dpv = vaddq_f32(DMO(dpc,0), xEv);
  dpv = vextq_f32(dpv, zerov, 1);
  for (q = Q-1; q >= 0; q--)
	{
	  dcv        = vmulq_f32(dpv, *tp); tp--;
	  DMO(dpc,q) = vaddq_f32(DMO(dpc,q), vaddq_f32(dcv, xEv));
	  dpv        = DMO(dpc,q);
	  MMO(dpc,q) = vaddq_f32(MMO(dpc,q), xEv);
	}

  /* phase 4: finish extending the DD paths */
  /* fully serialized for now */
  for (j = 1; j < 4; j++)	/* three passes: we've already done 1 segment, we need 4 total */
	{
dcv = vextq_f32(dcv, zerov, 1);
	  tp  = om->tfv + 8*Q - 1;	/* <*tp> now the [4 8 12 x] TDD quad */
	  for (q = Q-1; q >= 0; q--)
	    {
	      dcv        = vmulq_f32(dcv, *tp); tp--;
	      DMO(dpc,q) = vaddq_f32(DMO(dpc,q), dcv);
	    }
	}

  /* phase 5: add M->D paths */
  dcv = vextq_f32(DMO(dpc,0), zerov, 1);
  tp  = om->tfv + 7*Q - 3;	/* <*tp> is now the [4 8 12 x] Mk->Dk+1 quad */
  for (q = Q-1; q >= 0; q--)
	{
	  MMO(dpc,q) = vaddq_f32(MMO(dpc,q), vmulq_f32(dcv, *tp)); tp -= 7;
	  dcv        = DMO(dpc,q);
	}

  /* Sparse rescaling  */

  /* In rare cases [J3/119] scale factors from <fwd> are
   * insufficient and backwards will overflow. In this case, we
   * switch on the fly to using our own scale factors, different
   * from those in <fwd>. This will complicate subsequent
   * posterior decoding routines.
   */
  if (scale_mode == BWD_SCALE_FORWARD)
    {
      if (xB > 1.0e16) *has_own_scales = TRUE;

      if      (*has_own_scales)  xmx[i*p7X_NXCELLS+p7X_SCALE] = (xB > 1.0e4) ? xB : 1.0;
      else                           xmx[i*p7X_NXCELLS+p7X_SCALE] = fwd_xmx[i*p7X_NXCELLS+p7X_SCALE];
    }
  else if (scale_mode == BWD_SCALE_OWN)
    xmx[i*p7X_NXCELLS+p7X_SCALE] = (xB > 1.0e4) ? xB : 1.0;

  if (xmx[i*p7X_NXCELLS+p7X_SCALE] > 1.0)
	{
	  xE /= xmx[i*p7X_NXCELLS+p7X_SCALE];
	  xN /= xmx[i*p7X_NXCELLS+p7X_SCALE];
	  xJ /= xmx[i*p7X_NXCELLS+p7X_SCALE];
	  xB /= xmx[i*p7X_NXCELLS+p7X_SCALE];
	  xC /= xmx[i*p7X_NXCELLS+p7X_SCALE];
	  xBv = vmovq_n_f32(1.0 / xmx[i*p7X_NXCELLS+p7X_SCALE]);
	  for (q = 0; q < Q; q++) {
	    MMO(dpc,q) = vmulq_f32(MMO(dpc,q), xBv);
	    DMO(dpc,q) = vmulq_f32(DMO(dpc,q), xBv);
	    IMO(dpc,q) = vmulq_f32(IMO(dpc,q), xBv);
	  }
	  if (totscale != NULL) *totscale += log(xmx[i*p7X_NXCELLS+p7X_SCALE]);
	}

  /* Stores are separate only for pedagogical reasons: easy to
   * turn this into a more memory efficient version just by
   * deleting the stores.
   */
  xmx[i*p7X_NXCELLS+p7X_E] = xE;
  xmx[i*p7X_NXCELLS+p7X_N] = xN;
  xmx[i*p7X_NXCELLS+p7X_J] = xJ;
  xmx[i*p7X_NXCELLS+p7X_B] = xB;
  xmx[i*p7X_NXCELLS+p7X_C] = xC;
}


/* backward_row_0()
 * Backward row 0: only the N and B states, from row 1 in <dpp> and the
 * special states of row 1 in <xmx>. Writes row 0's special states into
 * <xmx> and returns its N value.
 */
static float
backward_row_0(const ESL_DSQ *dsq, const P7_OPROFILE *om, float *xmx, const float32x4_t *dpp)
{
  register float32x4_t mpv;
  register float32x4_t xBv;
  float xN, xB;
  int q;
  int Q       = p7O_NQF(om->M);
  float32x4_t *rp;
  float32x4_t *tp;

  xN = xmx[1*p7X_NXCELLS+p7X_N];
  tp  = om->tfv;          /* <*tp> is now the [1 5 9 13] TBMk transition quad  */
  rp  = om->rfv[dsq[1]];  /* <*rp> is now the [1 5 9 13] match emission quad   */
  xBv = vmovq_n_f32(0.0);
  for (q = 0; q < Q; q++)
    {
      mpv = vmulq_f32(MMO(dpp,q), *rp);        rp++;
      mpv = vmulq_f32(mpv,  *tp);        tp += 7;
      xBv = vaddq_f32(xBv,   mpv);
    }
  /* horizontal sum of xBv */
  esl_neon_hsum_float((esl_neon_128f_t) xBv, &xB);

  xN = (xB * om->xf[p7O_N][p7O_MOVE]) + (xN * om->xf[p7O_N][p7O_LOOP]);

  xmx[p7X_B]     = xB;
  xmx[p7X_C]     = 0.0;
  xmx[p7X_J]     = 0.0;
  xmx[p7X_N]     = xN;
  xmx[p7X_E]     = 0.0;
  xmx[p7X_SCALE] = 1.0;
  return xN;
}


static int
backward_engine(int do_full, const ESL_DSQ *dsq, int L, const P7_OPROFILE *om, const P7_OMX *fwd, P7_OMX *bck, P7_OMX *pp, float *opt_sc)
{
  float xN;
  int i;
  int q;
  int Q       = p7O_NQF(om->M);
  float32x4_t *dpc;
  float32x4_t *dpp;

  /* initialize the L row. */
  bck->M = om->M;
  bck->L = L;
  bck->has_own_scales = FALSE;	/* backwards scale factors are *usually* given by <fwd> */
  dpc = bck->dpf[L * do_full];
  backward_row_L(om, fwd->xmx, bck->xmx, &bck->totscale, dpc, L, BWD_SCALE_FORWARD);
  if (pp != NULL) backward_decode_row(om, fwd, bck, dpc, pp, L, Q);

#if eslDEBUGLEVEL > 0
  if (bck->debugging) p7_omx_DumpFBRow(bck, TRUE, L, 9, 4, bck->xmx[L*p7X_NXCELLS+p7X_E], bck->xmx[L*p7X_NXCELLS+p7X_N], bck->xmx[L*p7X_NXCELLS+p7X_J], bck->xmx[L*p7X_NXCELLS+p7X_B], bck->xmx[L*p7X_NXCELLS+p7X_C]);	/* logify=TRUE, <rowi>=L, width=9, precision=4*/
#endif

  /* main recursion */
  for (i = L-1; i >= 1; i--)	/* backwards stride */
    {
      /* phase 1. B(i) collected. Old row destroyed, new row contains
       *    complete I(i,k), partial {MD}(i,k) w/ no {MD}->{DE} paths yet.
       */
      dpc = bck->dpf[i     * do_full];
      dpp = bck->dpf[(i+1) * do_full];
      backward_row(dsq, om, fwd->xmx, bck->xmx, &bck->totscale, &bck->has_own_scales, dpc, dpp, i, BWD_SCALE_FORWARD);
      if (pp != NULL) backward_decode_row(om, fwd, bck, dpc, pp, i, Q);

#if eslDEBUGLEVEL > 0
      if (bck->debugging) p7_omx_DumpFBRow(bck, TRUE, i, 9, 4, bck->xmx[i*p7X_NXCELLS+p7X_E], bck->xmx[i*p7X_NXCELLS+p7X_N], bck->xmx[i*p7X_NXCELLS+p7X_J], bck->xmx[i*p7X_NXCELLS+p7X_B], bck->xmx[i*p7X_NXCELLS+p7X_C]);	/* logify=TRUE, <rowi>=i, width=9, precision=4*/
#endif
    } /* thus ends the loop over sequence positions i */

  /* Termination at i=0, where we can only reach N,B states. */
  dpp = bck->dpf[1 * do_full];
  xN  = backward_row_0(dsq, om, bck->xmx, dpp);

#if eslDEBUGLEVEL > 0
  dpc = bck->dpf[0];
  for (q = 0; q < Q; q++) /* Not strictly necessary, but if someone's looking at DP matrices, this is nice to do: */
    MMO(dpc,q) = DMO(dpc,q) = IMO(dpc,q) = vmovq_n_f32(0.0);
  if (bck->debugging) p7_omx_DumpFBRow(bck, TRUE, 0, 9, 4, bck->xmx[p7X_E], bck->xmx[p7X_N],  bck->xmx[p7X_J], bck->xmx[p7X_B],  bck->xmx[p7X_C]);	/* logify=TRUE, <rowi>=0, width=9, precision=4*/
#endif

  if       (isnan(xN))        ESL_EXCEPTION(eslERANGE, "backward score is NaN");
  else if  (L>0 && xN == 0.0) ESL_EXCEPTION(eslERANGE, "backward score underflow (is 0.0)");    /* if L==0, xN *should* be 0.0 [J5/118]*/
  else if  (isinf(xN) == 1)   ESL_EXCEPTION(eslERANGE, "backward score overflow (is infinity)");

  if (opt_sc != NULL) *opt_sc = bck->totscale + log(xN);

  /* Posterior decoding: scale each row by its scale product, as p7_Decoding() does */
  if (pp != NULL)
    {
      float  scaleproduct = 1.0 / bck->xmx[p7X_N];
      float32x4_t  totrv;
      float32x4_t *ppv;

      pp->M = om->M;
      pp->L = L;

      ppv = pp->dpf[0];
      for (q = 0; q < Q; q++)
        MMO(ppv,q) = DMO(ppv,q) = IMO(ppv,q) = vmovq_n_f32(0.0);
      pp->xmx[p7X_E] = 0.0;
      pp->xmx[p7X_N] = 0.0;
      pp->xmx[p7X_J] = 0.0;
      pp->xmx[p7X_C] = 0.0;
      pp->xmx[p7X_B] = 0.0;

      for (i = 1; i <= L; i++)
        {
          ppv   = pp->dpf[i];
          totrv = vmovq_n_f32(scaleproduct * fwd->xmx[i*p7X_NXCELLS+p7X_SCALE]);
          for (q = 0; q < Q; q++)
            {
              MMO(ppv,q) = vmulq_f32(MMO(ppv,q), totrv);
              IMO(ppv,q) = vmulq_f32(IMO(ppv,q), totrv);
            }
          pp->xmx[i*p7X_NXCELLS+p7X_N] *= scaleproduct;
          pp->xmx[i*p7X_NXCELLS+p7X_J] *= scaleproduct;
          pp->xmx[i*p7X_NXCELLS+p7X_C] *= scaleproduct;

          if (bck->has_own_scales) scaleproduct *= fwd->xmx[i*p7X_NXCELLS+p7X_SCALE] /  bck->xmx[i*p7X_NXCELLS+p7X_SCALE];
        }
      if (isinf(scaleproduct)) return eslERANGE;
    }
  return eslOK;
}

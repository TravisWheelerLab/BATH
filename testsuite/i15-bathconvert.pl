#! /usr/bin/perl

# Checks that bathconvert can still read old model formats.
#
# HMMER2.0 case is bug #h80 (HMMER): hmmconvert can't read H2 Nucleic
# files. Based on HMMER's i15-hmmconvert.pl, adapted for bathconvert.
# BATH only handles amino models, so the nucleic case from the original
# test is dropped.
#
# BATH 1.x case checks that bathconvert reads a real BATH 1.x model
# correctly: BATH 1.x wrote a single frameshift tau ("STATS LOCAL FS
# FORWARD"), which doesn't map onto the FS3/FS5 split BATH 2.0 scores
# against, so a plain conversion (no --fs) should write no frameshift
# stats at all rather than a stale or invented value; --fs should
# compute real FS3/FS5 values.
#
# Usage:   ./i15-bathconvert.pl <builddir> <srcdir> <tmpfile prefix>
# Example: ./i15-bathconvert.pl ..         ..       tmpfoo

BEGIN {
    $builddir  = shift;
    $srcdir    = shift;
    $tmppfx    = shift;
}

# Verify that we have all the executables we need for the test.
if (! -x "$builddir/src/bathconvert") { die "FAIL: didn't find bathconvert binary in $builddir/src\n";  }

# Create our test files (data embedded in script: see end of file)
&h2_aa_file("$tmppfx.aa.hmm");
&bath1_aa_file("$tmppfx.bath1.bhmm");

@output = `$builddir/src/bathconvert $tmppfx.aa.bhmm $tmppfx.aa.hmm 2>&1`;
if ($? != 0) { die "FAIL: bathconvert of H2 protein model failed\n"; }

@output = `$builddir/src/bathconvert $tmppfx.bath1_plain.bhmm $tmppfx.bath1.bhmm 2>&1`;
if ($? != 0) { die "FAIL: bathconvert of BATH 1.x model failed\n"; }
&check_no_fs_stats("$tmppfx.bath1_plain.bhmm", "plain bathconvert of a BATH 1.x model");

@output = `$builddir/src/bathconvert --fs $tmppfx.bath1_fs.bhmm $tmppfx.bath1.bhmm 2>&1`;
if ($? != 0) { die "FAIL: bathconvert --fs of BATH 1.x model failed\n"; }
($fs3, $fs5) = &get_fs_taus("$tmppfx.bath1_fs.bhmm");
if (! defined $fs3 || ! defined $fs5)     { die "FAIL: bathconvert --fs of a BATH 1.x model didn't write FS3/FS5 stats\n"; }
if ($fs3 == -99999.0 || $fs5 == -99999.0) { die "FAIL: bathconvert --fs of a BATH 1.x model left FS3/FS5 stats unset\n"; }


print "ok\n";
unlink "$tmppfx.aa.hmm";
unlink "$tmppfx.aa.bhmm";
unlink "$tmppfx.bath1.bhmm";
unlink "$tmppfx.bath1_plain.bhmm";
unlink "$tmppfx.bath1_fs.bhmm";


sub check_no_fs_stats
{
    my ($bhmmfile, $label) = @_;
    open(BHMM, $bhmmfile) || die "FAIL: couldn't open $bhmmfile\n";
    while (<BHMM>) {
	if (/^STATS LOCAL FS/)   { die "FAIL: $label: unexpected frameshift STATS line: $_"; }
	if (/^FRAMESHIFT PROB/)  { die "FAIL: $label: unexpected FRAMESHIFT PROB line: $_"; }
    }
    close BHMM;
}

sub get_fs_taus
{
    my ($bhmmfile) = @_;
    my ($fs3, $fs5);
    open(BHMM, $bhmmfile) || die "FAIL: couldn't open $bhmmfile\n";
    while (<BHMM>) {
	if (/^STATS LOCAL FS3 FORWARD\s+(\S+)/) { $fs3 = $1; }
	if (/^STATS LOCAL FS5 FORWARD\s+(\S+)/) { $fs5 = $1; }
    }
    close BHMM;
    return ($fs3, $fs5);
}
exit 0;


